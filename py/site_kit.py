def nav_html(mode: str, active: str = "") -> str:
    """mode 'jekyll' (Liquid, for the layout) or 'visuals' (pages in docs/visuals/, relative links)."""
    def link(path, label):
        if mode == "jekyll":
            test = f"page.url == '/{path}'" + (" or page.url == '/'" if path == "index.html" else "")
            return f"<a{{% if {test} %}} class=\"on\"{{% endif %}} href=\"{{{{ '/{path}' | relative_url }}}}\">{label}</a>"
        on = ' class="on"' if path == active else ""
        return f'<a{on} href="../{path}">{label}</a>'

    rows = [("Documentation", DOC_PAGES), ("Roundtrip", ROUNDTRIP_PAGES), ("Visuals", VISUAL_PAGES), ("Explorer", EXPLORER_PAGES)]
    return "<nav>" + "".join(
        f'<div class="grp"><span class="lab">{name}</span><span class="lnk">' + "".join(link(p, t) for p, t in pages) + "</span></div>"
        for name, pages in rows) + "</nav>"


def layout_html() -> str:
    return ("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
            "<title>{% if page.title %}{{ page.title }} · {% endif %}{{ site.title }}</title>\n"
            "<link rel=\"stylesheet\" href=\"{{ '/assets/site.css' | relative_url }}\">\n</head>\n<body>\n<main>\n"
            + nav_html("jekyll") + "\n<article class=\"prose\">\n{{ content }}\n</article>\n</main>\n</body>\n</html>\n")


def write_assets() -> None:
    """docs/assets/site.css, docs/assets/fonts/, docs/_layouts/default.html."""
    (DOCS / "assets" / "fonts").mkdir(parents=True, exist_ok=True)
    (DOCS / "assets" / "site.css").write_text(CSS, encoding="utf-8", newline="\n")
    for f in sorted(FONTS.glob("FiraSans-*.ttf")):
        shutil.copyfile(f, DOCS / "assets" / "fonts" / f.name)
    (DOCS / "_layouts").mkdir(parents=True, exist_ok=True)
    (DOCS / "_layouts" / "default.html").write_text(layout_html(), encoding="utf-8", newline="\n")
