"""Step "explorer": the AMT Explorer of the Mini-AMT, with the three chains to choose from.

Reads   data/chains-source.csv     the source strings of the chains (via step_chains: weights, types, methods)
        ontology/mini-amt.ttl      model M1 (concepts, roles, axioms; ProductLogic)
Writes  docs/explorer/data/chain-A.ttl, chain-B.ttl, chain-C.ttl   ontology M1 + the hextuples of one chain
        docs/explorer/data/examples.json                          the list the Explorer reads

The page itself (docs/explorer/index.html), the scripts (js/), the libraries (vendor/) and the palette are static
files, adapted from the Explorer of https://github.com/alpaca-fair-framework/amt-engine (MIT licence, see
docs/explorer/vendor/README.md). The Explorer runs completely in the browser: it parses the Turtle file, draws the
graph and does the reasoning in JavaScript, so it works on GitHub Pages without a server.

A check reads every written file back and compares its statement count with the edges of the chain.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import step_chains as C  # noqa: E402
from mini_amt_utils import ONTOLOGY, ROOT  # noqa: E402

OUT = ROOT / "docs" / "explorer" / "data"
FRAME = ("# Generated by main.py (step: explorer) from data/chains-source.csv and ontology/mini-amt.ttl. Do not edit by hand.\n"
         "# Chain {chain}: {what}\n"
         "# Part 1 is model M1 (ontology/mini-amt.ttl), part 2 the instances and hextuples of the chain.\n"
         "# Frequency shares (mini:frequencyShare ...) are additional information, not weights; the Explorer ignores them.\n\n")


def title(chain: str, rows: list[dict]) -> str:
    r = rows[0]
    return (f"Chain {chain} - {r['potter']}: {', '.join(x['potform_text'] for x in rows)} | {r['centre_text']}")


def chain_text(chain: str, rows: list[dict], ontology: str) -> tuple[str, int]:
    edges, nodes = C.build_edges(rows)
    body = [C.nodes_ttl(nodes), "", C.evidence_ttl(edges), ""]
    if any(e.get("frequency") for e in edges):
        body += [f'mini:{C.F.METHOD} rdfs:label "{C.F.LABEL_EN}"@en, "{C.F.LABEL_DE}"@de .', ""]
    body += [C.statement_ttl(e, freq=True) for e in edges]
    what = "; ".join(f"carrier {r['carrier_id']}: {r['potform_text']} / {r['centre_text']}" for r in rows)
    head = FRAME.format(chain=chain, what=what)
    return head + ontology.rstrip() + "\n\n" + C.HEADER + "\n" + "\n".join(body) + "\n", len(edges)


def main() -> int:
    rows = C.read_source()
    OUT.mkdir(parents=True, exist_ok=True)
    ontology = ONTOLOGY.read_text(encoding="utf-8")
    listing = []
    for chain in sorted({r["chain"] for r in rows}):
        sel = [r for r in rows if r["chain"] == chain]
        text, n = chain_text(chain, sel, ontology)
        name = f"chain-{chain}.ttl"
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        got = text.count("rdf:subject ")
        if got != n:
            raise AssertionError(f"{name}: {got} statements written, {n} expected")
        listing.append({"file": name, "title": title(chain, sel)})
    (OUT / "examples.json").write_text(json.dumps(listing, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"explorer: {len(listing)} chains written to docs/explorer/data/ ({', '.join(x['file'] for x in listing)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
